// Generates `motion.css` (run `pnpm --filter @mc/ui generate`): CSS custom properties for every spring
// (Motion's `spring()` turned into a CSS `linear()` easing) plus the CSS-only motion utilities.
import { spring as springGenerator } from 'motion';

import { css, feedback, loop, press, spring, tween } from './tokens.ts';

const HEADER = '/* GENERATED by packages/ui/scripts/generate.ts from src/motion — do not edit by hand. */\n';

/** `500ms linear(…)` for a spring token, as Motion would animate it. */
export function springCss(name: keyof typeof spring): string {
  const { visualDuration, bounce } = spring[name];
  return String(springGenerator(visualDuration, bounce));
}

export function motionCss(): string {
  const springs = (Object.keys(spring) as (keyof typeof spring)[]).map(
    (name) => `  --mc-spring-${name}: ${springCss(name)};`,
  );
  const scales = Object.entries(press).map(([kind, scale]) => `  --mc-press-${kind}: ${String(scale)};`);
  // Browsers without CSS linear() (iOS < 17.2, old WebViews) get the iOS curve at the spring's visual duration.
  const fallbacks = (Object.keys(spring) as (keyof typeof spring)[]).map(
    (name) =>
      `    --mc-spring-${name}: ${String(Math.round(spring[name].visualDuration * 1000))}ms var(--mc-ease-ios);`,
  );
  const ms = (seconds: number) => `${String(Math.round(seconds * 1000))}ms`;
  const last = feedback.shakePx.length - 1;
  const shakeFrames = feedback.shakePx.map(
    (px, index) =>
      `  ${String(Math.round((index * 100) / last))}% {
    transform: translateX(${String(px)}px);
  }`,
  );
  return `${HEADER}
:root {
${springs.join('\n')}
  --mc-ease-ios: ${css.ios.easing};
  --mc-duration-ios: ${String(css.ios.durationMs)}ms;
  --mc-tween-fade: ${ms(tween.fade.duration)} cubic-bezier(${tween.fade.ease.join(', ')});
  --mc-tween-quick: ${ms(tween.quick.duration)} ease-out;
${scales.join('\n')}
}

@supports not (transition-timing-function: linear(0, 1)) {
  :root {
${fallbacks.join('\n')}
  }
}

/*
 * Press feedback (08 §5.1): the Pressable primitive sets [data-pressed] synchronously on pointerdown; the
 * transform runs on the compositor with the spring.snappy curve. Browsers without CSS linear() keep the
 * cubic-bezier fallback declared first.
 */
@utility pressable {
  transform: scale(1);
  transition: transform var(--mc-duration-ios) var(--mc-ease-ios);
  transition: transform var(--mc-spring-snappy);
  touch-action: manipulation;
  user-select: none;
  -webkit-user-select: none;
  -webkit-touch-callout: none;
  &[data-pressed] {
    transform: scale(var(--mc-press-scale, var(--mc-press-button)));
  }
}

@utility press-card {
  --mc-press-scale: var(--mc-press-card);
}

@utility press-fab {
  --mc-press-scale: var(--mc-press-fab);
}

/* CSS-only transitions (banners, skeleton → content). Reduced motion keeps only the fade. */
@utility transition-ios {
  transition-property: opacity, transform;
  transition-duration: var(--mc-duration-ios);
  transition-timing-function: var(--mc-ease-ios);
  @media (prefers-reduced-motion: reduce) {
    transition-property: opacity;
  }
}

/* Color/opacity state changes (chips, switch track, tab labels) on the spring.snappy curve. */
@utility transition-state {
  transition: color var(--mc-spring-snappy), background-color var(--mc-spring-snappy),
    border-color var(--mc-spring-snappy), opacity var(--mc-spring-snappy), transform var(--mc-spring-snappy);
  @media (prefers-reduced-motion: reduce) {
    transition: color ${ms(tween.fade.duration)}, background-color ${ms(tween.fade.duration)},
      border-color ${ms(tween.fade.duration)}, opacity ${ms(tween.fade.duration)};
  }
}

/* Image placeholder → real image (08 §5.4): opacity only, no scale pop. */
@utility transition-image {
  transition: opacity ${String(css.imageInMs)}ms var(--mc-ease-ios);
}

/* Sliding selection indicators (08 §5.2): segmented thumb (spring.smooth), tab underline (spring.snappy). */
@utility transition-thumb {
  transition: transform var(--mc-spring-smooth);
  @media (prefers-reduced-motion: reduce) {
    transition: none;
  }
}

/* Prayer strip highlight sliding to the next prayer's cell (08 §5.5, spring.gentle). */
@utility transition-highlight {
  transition: transform var(--mc-spring-gentle);
  @media (prefers-reduced-motion: reduce) {
    transition: none;
  }
}

@utility transition-indicator {
  transition: transform var(--mc-spring-snappy);
  @media (prefers-reduced-motion: reduce) {
    transition: none;
  }
}

/* Invalid form field (08 §5.10): a short horizontal shake; none with reduced motion. */
@keyframes mc-shake {
${shakeFrames.join('\n')}
}

@utility shake {
  animation: mc-shake ${String(feedback.shakeMs)}ms ease-in-out;
  @media (prefers-reduced-motion: reduce) {
    animation: none;
  }
}

/* Tap ripple (keys, Ameen): from the element's center, or from the tap point when --mc-ripple-x/-y are set (Ameen,
   08 §5.6); none with reduced motion. */
@keyframes mc-ripple {
  from {
    transform: scale(0);
    opacity: 0.35;
  }
  to {
    transform: scale(2.4);
    opacity: 0;
  }
}

@utility ripple {
  position: relative;
  overflow: hidden;
  &::after {
    content: '';
    position: absolute;
    inset-block-start: var(--mc-ripple-y, 50%);
    /* Physical on purpose: the tap point is a pointer coordinate measured from the box's left edge, in any direction. */
    left: var(--mc-ripple-x, 50%);
    translate: -50% -50%;
    width: var(--mc-ripple-size, 50%);
    aspect-ratio: 1;
    border-radius: 9999px;
    background-color: var(--color-mint-200);
    opacity: 0;
    pointer-events: none;
  }
  &[data-ripple]::after {
    animation: mc-ripple ${String(feedback.rippleMs)}ms ease-out;
  }
  @media (prefers-reduced-motion: reduce) {
    &[data-ripple]::after {
      animation: none;
    }
  }
}

/* Spinner: one compositor rotation per ${String(loop.spinnerMs)} ms. Kept with reduced motion (it is functional). */
@keyframes mc-spin {
  to {
    transform: rotate(360deg);
  }
}

@utility spin {
  animation: mc-spin ${String(loop.spinnerMs)}ms linear infinite;
}

/* Countdown under 10 minutes (08 §5.5): a soft pulsing dot (opacity + scale); static with reduced motion. */
@keyframes mc-pulse {
  50% {
    opacity: 0.35;
    transform: scale(0.7);
  }
}

@utility pulse-dot {
  animation: mc-pulse ${String(loop.pulseMs)}ms ease-in-out infinite;
  @media (prefers-reduced-motion: reduce) {
    animation: none;
  }
}

/* Skeleton (08 §5.4, §6): a highlight sweeps across on the compositor; static with reduced motion. */
@keyframes mc-shimmer {
  from {
    transform: translateX(-100%);
  }
  to {
    transform: translateX(100%);
  }
}

@utility skeleton {
  position: relative;
  overflow: hidden;
  background-color: var(--color-surface-muted);
  &::after {
    content: '';
    position: absolute;
    inset: 0;
    background-image: linear-gradient(
      90deg,
      transparent,
      color-mix(in srgb, var(--color-surface) 70%, transparent),
      transparent
    );
    animation: mc-shimmer ${String(loop.shimmerMs)}ms ease-in-out infinite;
  }
  @media (prefers-reduced-motion: reduce) {
    &::after {
      animation: none;
      opacity: 0;
    }
  }
}
`;
}
