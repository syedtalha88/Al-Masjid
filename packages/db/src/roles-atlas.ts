// Atlas applier input for 02 §4.3 (PHASE_01 T1.1). Atlas forbids `createRole`/`createUser` on every tier; custom
// roles and users are created through the Atlas Administration API (v2, checked 16 Oct 2026: POST
// /groups/{groupId}/customDBRoles/roles with `actions: [{action, resources: [{db, collection}]}]`, action names in
// UPPER_SNAKE_CASE per "Custom Role Actions"). `pnpm db:roles:atlas` writes infra/mongo/atlas-roles.json, which the
// VPS script infra/vps/atlas-users.sh applies — the server never needs Node or this package.
import { type Action, DB_USERS, type DbUser, roleName, rolePrivileges } from './roles.ts';

/** Atlas Administration API action names (docs: atlas/reference/custom-role-actions). */
export const ATLAS_ACTION: Readonly<Record<Action, string>> = {
  find: 'FIND',
  insert: 'INSERT',
  update: 'UPDATE',
  remove: 'REMOVE',
  createCollection: 'CREATE_COLLECTION',
  dropCollection: 'DROP_COLLECTION',
  collMod: 'COLL_MOD',
  createIndex: 'CREATE_INDEX',
  dropIndex: 'DROP_INDEX',
  listIndexes: 'LIST_INDEXES',
  listCollections: 'LIST_COLLECTIONS',
};

export interface AtlasCustomRole {
  readonly roleName: string;
  readonly actions: readonly { action: string; resources: readonly { db: string; collection: string }[] }[];
  readonly inheritedRoles: readonly never[];
}

/**
 * The Atlas custom role for one user in one database: one entry per action, listing every namespace it applies to.
 *
 * @param user - the privilege set (02 §4.3).
 * @param database - `MONGODB_DB_NAME` of the environment (`masjid_connect` on staging and production).
 */
export function atlasRole(user: DbUser, database: string): AtlasCustomRole {
  const byAction = new Map<string, { db: string; collection: string }[]>();
  for (const { namespace, actions } of rolePrivileges(user)) {
    for (const action of actions) {
      const name = ATLAS_ACTION[action];
      const resources = byAction.get(name) ?? [];
      resources.push({ db: database, collection: namespace ?? '' });
      byAction.set(name, resources);
    }
  }
  return {
    roleName: roleName(user, database),
    actions: [...byAction].sort(([a], [b]) => a.localeCompare(b)).map(([action, resources]) => ({ action, resources })),
    inheritedRoles: [],
  };
}

/** The file infra/mongo/atlas-roles.json: every user's role for `database`, plus the process each user belongs to. */
export function atlasRolesFile(database: string) {
  const process: Readonly<Record<DbUser, string>> = {
    mc_public: 'api-public',
    mc_admin: 'api-admin',
    mc_system: 'worker',
    mc_migrator: 'migrate',
  };
  return {
    $comment: 'Generated by `pnpm db:roles:atlas` from packages/db/src/roles.ts (02 §4.3) — do not edit by hand.',
    database,
    users: DB_USERS.map((user) => ({ user, process: process[user], role: atlasRole(user, database) })),
  };
}
